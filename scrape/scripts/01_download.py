"""
Step 1: Parse a PDBbind INDEX file, identify N-mer peptide binders,
compute DeltaG from Kd/Ki data, and download biological assembly CIFs
to pdb_cache/ (saved as <pdb_id>-<N>.cif).

Output: outputs/peptide_entries.tsv, pdb_cache/<pdb_id>-<N>.cif
        logs/01_download.log

Usage:
  python 01_download.py
  python 01_download.py --index ../inputs/INDEX_general_PL.2020
  python 01_download.py -v
"""

import argparse
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
_root = _here.parent
sys.path.insert(0, str(_root))

from modules.download import parse_index, download_entries
from modules.utils import save_tsv, setup_logging

# v2020R1 is a strict subset of v2020 (406 entries removed, 0 new, 314 changed
# binding data/resolution/year -- see PDBbindVersions/ sibling project), so it
# is the more current and preferred default.
DEFAULT_INDEX = _root / "inputs" / "INDEX_general_PL.2020R1.lst"
PDB_CACHE     = _root / "pdb_cache"
OUTPUTS_DIR   = _root / "outputs"
LOGS_DIR      = _root / "logs"
OUT_TSV       = OUTPUTS_DIR / "peptide_entries.tsv"
LOG_FILE      = LOGS_DIR / "01_download.log"
OUT_COLS      = ["pdb_id", "n_mer", "resolution", "year", "binding_type",
                 "dG_kcal", "dG_approx", "step1_reject", "temperature"]


def main():
    parser = argparse.ArgumentParser(
        description="Step 1: Parse PDBbind INDEX, compute ΔG, download assembly CIFs.")
    parser.add_argument("--index", default=DEFAULT_INDEX, type=Path,
                        help="PDBbind index file (default: scrape/inputs/INDEX_general_PL.2020R1.lst). "
                             "Relative paths are resolved from the current directory.")
    parser.add_argument("--temperature", default=300.0, type=float, metavar="K",
                        help="Fallback temperature in K (default: 300.0).")
    parser.add_argument("--clean", action="store_true",
                        help="Remove files generated by this step.")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="Print a brief start/done line to stdout.")
    parser.add_argument("--log", metavar="FILE", default=str(LOG_FILE),
                        help=f"Log file path (default: {LOG_FILE.name}).")
    args = parser.parse_args()

    if args.clean:
        if OUT_TSV.exists():
            OUT_TSV.unlink()
            print(f"Removed {OUT_TSV}")
        return

    log_file = Path(args.log)
    OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)
    _logger, stdout = setup_logging(log_file, args.verbose)

    index_file = Path(args.index)
    if not index_file.exists():
        sys.stderr.write(
            f"Error: PDBbind index file not found: {index_file}\n"
            f"  PDBbind data is not distributed with PepXPro. Download the index file from\n"
            f"  PDBbind+ (registration required) and copy it to:\n"
            f"    {DEFAULT_INDEX}\n"
            f"  or pass its location with --index FILE.\n"
            f"  See 'PDBbind data and licensing' in README.md.\n")
        sys.exit(1)

    if args.verbose:
        stdout.write("[scrape/01-download] starting ...\n")
        stdout.flush()

    print(f"Parsing {index_file} (fallback temperature: {args.temperature} K) ...")
    entries = parse_index(index_file, fallback_temp=args.temperature)
    print(f"  {len(entries)} peptide-mer entries found")

    before = len(entries)
    entries = [e for e in entries if e["binding_type"] in ("Kd", "Ki")]
    print(f"  {before - len(entries)} dropped (IC50 or no binding data)")
    print(f"  {len(entries)} entries remaining (Kd/Ki only)")

    rejected     = [e for e in entries if e["step1_reject"]]
    downloadable = [e for e in entries if not e["step1_reject"]]
    print(f"  {len(rejected)} rejected at step 1 (e.g. covalent complex)")
    print(f"  {len(downloadable)} to download")

    save_tsv(entries, OUT_TSV, OUT_COLS)
    print(f"  Written {OUT_TSV}")

    pdb_ids = [e["pdb_id"] for e in downloadable]
    counts, errors = download_entries(pdb_ids, PDB_CACHE)
    print(f"Done. ok={counts['ok']} cached={counts['cached']} errors={counts['error']}")
    if errors:
        print("Download errors:")
        for pid, msg in errors:
            print(f"  {pid}: {msg}")

    if args.verbose:
        stdout.write(
            f"[scrape/01-download] done  —  {len(entries)} entries"
            f"  ok={counts['ok']} cached={counts['cached']} errors={counts['error']}\n"
        )
        stdout.flush()


if __name__ == "__main__":
    main()
