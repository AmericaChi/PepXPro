"""
Step 3: Merge filtered_systems.tsv with peptide_entries.tsv and write
a human-readable summary table.

Output columns:
    pdb_id         - PDB accession code
    receptor       - e.g. "AB:300" (chains A+B, 300 total residues)
    peptide        - e.g. "C:12" (actual post-fix residue count)
    dG_kcal_mol    - DeltaG at 300 K (kcal/mol); Kd/Ki only
    binding_type   - Kd / Ki / IC50

Input:  peptide_entries.tsv, filtered_systems.tsv
Output: summary.tsv
Run:    mamba activate mdtools && python 03_summary.py 2>&1 | tee step3_run.log
"""

import argparse
from pathlib import Path

ENTRIES_TSV  = Path("peptide_entries.tsv")
FILTERED_TSV = Path("filtered_systems.tsv")
OUT_TSV      = Path("summary.tsv")


def load_tsv(path):
    """Return list of dicts from a tab-separated file with a header row."""
    rows = []
    with open(path, encoding="ascii") as fh:
        header = fh.readline().strip().split("\t")
        for line in fh:
            if not line.strip():
                continue
            parts = line.rstrip("\n").split("\t")
            rows.append(dict(zip(header, parts)))
    return rows


def format_receptor(chain_ids_str, length_str):
    """'A,B', '300'  ->  'AB:300'"""
    chains = "".join(chain_ids_str.split(","))
    return f"{chains}:{length_str}"


def format_peptide(chain_id, length_str):
    """'C', '12'  ->  'C:12'"""
    return f"{chain_id}:{length_str}"


def main():
    parser = argparse.ArgumentParser(
        description="Step 3: Merge filtered_systems.tsv with peptide_entries.tsv "
                    "and write summary.tsv.")
    parser.add_argument("--clean", action="store_true",
                        help="Remove files generated by this step (summary.tsv).")
    args = parser.parse_args()

    if args.clean:
        if OUT_TSV.exists():
            OUT_TSV.unlink()
            print(f"Removed {OUT_TSV}")
        return

    entries_rows  = load_tsv(ENTRIES_TSV)
    filtered_rows = load_tsv(FILTERED_TSV)

    # Index entries by pdb_id
    entries_map = {r["pdb_id"]: r for r in entries_rows}

    # Only accepted systems
    accepted = [r for r in filtered_rows if r.get("accepted") == "Y"]
    print(f"Accepted systems: {len(accepted)}")

    out_cols = ["pdb_id", "receptor", "peptide", "dG_kcal_mol", "binding_type"]

    out_rows = []
    for row in accepted:
        pdb_id = row["pdb_id"]
        entry  = entries_map.get(pdb_id, {})

        receptor_str = format_receptor(row["receptor_chains"], row["receptor_length"])
        peptide_str  = format_peptide(row["peptide_chain"], row["peptide_length"])

        dG_raw   = entry.get("dG_kcal", "NA")
        dG_str   = dG_raw

        btype    = entry.get("binding_type", "NA")

        try:
            dG_sort = float(dG_raw)
        except (ValueError, TypeError):
            dG_sort = float("inf")  # NA values go last

        out_rows.append((dG_sort, [pdb_id, receptor_str, peptide_str, dG_str, btype]))

    out_rows.sort(key=lambda x: x[0])

    with open(OUT_TSV, "w", encoding="ascii") as fh:
        fh.write("\t".join(out_cols) + "\n")
        for _, out_row in out_rows:
            fh.write("\t".join(out_row) + "\n")

    print(f"Written {OUT_TSV}")

    # Print first few lines as a preview
    print("\nPreview (first 10 rows):")
    print("\t".join(out_cols))
    with open(OUT_TSV, encoding="ascii") as fh:
        fh.readline()  # skip header
        for _, line in zip(range(10), fh):
            print(line, end="")


if __name__ == "__main__":
    main()
